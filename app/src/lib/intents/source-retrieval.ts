import type { ToolSpec } from '../chat/redpill'
import type { SourceIndex } from './source-index'

export interface SourceEntry {
	artifactId: string
	intentId: string
	title: string
	kind: string
	summary?: string | null
	createdAt?: string
}
export interface SourceText {
	content: string
	complete: boolean
	/** Generated text is an interpretation, not an independent original source. */
	generated?: boolean
	textArtifactId?: string
	chunks?: Array<{ artifactId: string; start: number; endExclusive: number }>
}
export interface SourceProvider {
	entries(): SourceEntry[]
	index: SourceIndex
	resolve?(key: string): SourceEntry[]
	coverage?(scope?: { intent?: unknown; before?: unknown }): {
		pending: number
		unavailable: number
		totalSources: number
		inventoryComplete?: boolean
	}
	read(entry: SourceEntry): Promise<SourceText>
}
export const SOURCE_PAGE_CHARS = 12000

